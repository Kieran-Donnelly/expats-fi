export function hikeHslUrl(hike: HikeGuide) {
  const destination = `${hike.name}, ${hike.start}::${hike.latitude},${hike.longitude}`
  return `https://reittiopas.hsl.fi/reitti/-/${encodeURIComponent(destination)}/?locale=en`
}

export function hikeGoogleMapsUrl(hike: HikeGuide) {
  return `https://www.google.com/maps/dir/?api=1&destination=${encodeURIComponent(`${hike.latitude},${hike.longitude}`)}`
}
